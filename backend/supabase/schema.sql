on conflict (slug) do nothing;

create table if not exists public.chunk_embeddings (
  chunk_id bigint not null references public.evidence_chunks(id) on delete cascade,
  profile_id uuid not null references public.embedding_profiles(id) on delete cascade,
  embedding vector not null,
  input_hash text not null,
  created_at timestamptz not null default now(),
  primary key (chunk_id, profile_id)
);

create table if not exists public.analysis_runs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  stock_id bigint not null references public.stocks(id) on delete cascade,
  question text,
  final_summary text,
  guardrail_status text not null default 'passed',
  risk_level text,
  created_at timestamptz not null default now()
);

create table if not exists public.agent_outputs (
  id bigint generated by default as identity primary key,
  analysis_run_id uuid not null references public.analysis_runs(id) on delete cascade,
  agent_name text not null,
  output_json jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists public.claim_evidence (
  claim_id text not null,
  analysis_run_id uuid not null references public.analysis_runs(id) on delete cascade,
  evidence_document_id bigint not null references public.evidence_documents(id) on delete cascade,
  primary key (claim_id, evidence_document_id)
);

create table if not exists public.token_usage (
  id bigint generated by default as identity primary key,
  analysis_run_id uuid not null references public.analysis_runs(id) on delete cascade,
  model_name text not null,
  prompt_tokens integer not null default 0,
  completion_tokens integer not null default 0,
  total_tokens integer not null default 0,
  created_at timestamptz not null default now()
);

-- The project disables "Automatically expose new tables", so Data API access
-- is granted explicitly. Public market/evidence data is read-only. User-owned
-- records still require an authenticated JWT and are constrained by RLS below.
grant usage on schema public to anon, authenticated;

-- Server-only secret keys map to service_role. This role still needs SQL
-- privileges even though it bypasses RLS.
grant usage on schema public to service_role;
grant all privileges on all tables in schema public to service_role;
grant all privileges on all sequences in schema public to service_role;

alter default privileges in schema public
  grant all privileges on tables to service_role;
alter default privileges in schema public
  grant all privileges on sequences to service_role;

grant select on table
  public.stocks,
  public.stock_prices,
  public.technical_indicators,
  public.financial_facts,
  public.evidence_documents,
  public.evidence_chunks,
  public.macro_series,
  public.macro_observations,
  public.embedding_profiles,
  public.chunk_embeddings
to anon, authenticated;

grant select, insert, delete on table public.watchlists to authenticated;
grant select, insert on table public.analysis_runs to authenticated;
grant select on table
  public.agent_outputs,
  public.claim_evidence,
  public.token_usage
to authenticated;

alter table public.watchlists enable row level security;
alter table public.analysis_runs enable row level security;
alter table public.agent_outputs enable row level security;
alter table public.token_usage enable row level security;
alter table public.macro_series enable row level security;
alter table public.macro_observations enable row level security;

create policy "Public macro series are readable"
  on public.macro_series for select using (true);

create policy "Public macro observations are readable"
  on public.macro_observations for select using (true);

create policy "Users can manage their own watchlist"
  on public.watchlists for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "Users can read their own analysis runs"
  on public.analysis_runs for select
  using (auth.uid() = user_id);

create policy "Users can create their own analysis runs"
  on public.analysis_runs for insert
  with check (auth.uid() = user_id);

create policy "Users can read outputs for their analysis runs"
  on public.agent_outputs for select
  using (
    exists (
      select 1 from public.analysis_runs
      where analysis_runs.id = agent_outputs.analysis_run_id
        and analysis_runs.user_id = auth.uid()
    )
  );

create policy "Users can read token usage for their analysis runs"
  on public.token_usage for select
  using (
    exists (
      select 1 from public.analysis_runs
      where analysis_runs.id = token_usage.analysis_run_id
        and analysis_runs.user_id = auth.uid()
    )
  );
