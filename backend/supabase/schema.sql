-- AI Bull vs Bear database schema for Supabase.
-- Run this in the Supabase SQL Editor after enabling the pgvector extension.

create extension if not exists vector;

create table if not exists public.stocks (
  id bigint generated by default as identity primary key,
  ticker text not null unique,
  company_name text not null,
  exchange text not null,
  sector text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.watchlists (
  user_id uuid not null references auth.users(id) on delete cascade,
  stock_id bigint not null references public.stocks(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, stock_id)
);

create table if not exists public.stock_prices (
  id bigint generated by default as identity primary key,
  stock_id bigint not null references public.stocks(id) on delete cascade,
  trading_date date not null,
  open numeric(14, 4) not null,
  high numeric(14, 4) not null,
  low numeric(14, 4) not null,
  close numeric(14, 4) not null,
  volume bigint not null,
  unique (stock_id, trading_date)
);

create table if not exists public.technical_indicators (
  id bigint generated by default as identity primary key,
  stock_id bigint not null references public.stocks(id) on delete cascade,
  trading_date date not null,
  rsi numeric(8, 4),
  macd numeric(14, 6),
  macd_signal numeric(14, 6),
  moving_average_20 numeric(14, 6),
  moving_average_50 numeric(14, 6),
  volatility numeric(8, 4),
  volume_spike boolean not null default false,
  unique (stock_id, trading_date)
);

create table if not exists public.financial_facts (
  id bigint generated by default as identity primary key,
  stock_id bigint not null references public.stocks(id) on delete cascade,
  taxonomy text not null,
  concept text not null,
  label text not null,
  description text,
  unit text not null,
  value numeric not null,
  period_start date not null,
  period_end date not null,
  fiscal_year integer,
  fiscal_period text,
  form text not null check (form in ('10-K', '10-Q', '8-K', '20-F', '40-F', '6-K')),
  filed_at date not null,
  accession_number text not null,
  frame text,
  source_url text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (
    stock_id,
    taxonomy,
    concept,
    unit,
    period_start,
    period_end,
    accession_number
  )
);

create index if not exists financial_facts_lookup_idx
  on public.financial_facts (
    stock_id,
    concept,
    period_end desc,
    filed_at desc
  );

create table if not exists public.evidence_documents (
  id bigint generated by default as identity primary key,
  stock_id bigint not null references public.stocks(id) on delete cascade,
  source_type text not null check (source_type in ('news', 'filing', 'technical')),
  external_id text,
  title text not null,
  url text,
  published_at timestamptz,
  raw_text text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create unique index if not exists evidence_documents_external_id_idx
  on public.evidence_documents (external_id);

create table if not exists public.evidence_chunks (
  id bigint generated by default as identity primary key,
  document_id bigint not null references public.evidence_documents(id) on delete cascade,
  chunk_text text not null,
  embedding vector(1536),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists evidence_chunks_embedding_idx
  on public.evidence_chunks using ivfflat (embedding vector_cosine_ops)
  with (lists = 100);

create table if not exists public.macro_series (
  code text primary key,
  name text not null,
  source text not null check (source in ('fred', 'eia', 'treasury', 'fomc', 'cme')),
  unit text not null,
  frequency text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.macro_observations (
  series_code text not null references public.macro_series(code) on delete cascade,
  observation_date date not null,
  value numeric not null,
  metadata jsonb not null default '{}'::jsonb,
  retrieved_at timestamptz not null default now(),
  primary key (series_code, observation_date)
);

create index if not exists macro_observations_recent_idx
  on public.macro_observations (series_code, observation_date desc);

create table if not exists public.embedding_profiles (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  provider text not null,
  model text not null,
  dimensions integer not null check (dimensions between 1 and 16000),
  distance_metric text not null default 'cosine'
    check (distance_metric in ('cosine', 'inner_product', 'l2')),
  normalization text not null default 'none',
  modality text not null default 'text'
    check (modality in ('text', 'multimodal')),
  query_instruction text,
  document_instruction text,
  preprocessing_version text not null default 'v1',
  status text not null default 'test'
    check (status in ('test', 'active', 'retired')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

insert into public.embedding_profiles (
  id,
  slug,
  provider,
  model,
  dimensions,
  distance_metric,
  normalization,
  modality,
  preprocessing_version,
  status,
  metadata
)
values (
